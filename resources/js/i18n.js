const defaultLocale = 'zh-CN';
const storedLocale = typeof window === 'undefined' ? null : window.localStorage.getItem('ui_locale');
const locale = ref(messages[storedLocale] ? storedLocale : defaultLocale);

watch(locale, (value) => {
    if (typeof window !== 'undefined') {
        window.localStorage.setItem('ui_locale', value);
        document.documentElement.lang = value;
    }
}, { immediate: true });

function translate(key, replacements = {}) {
    const text = messages[locale.value]?.[key] ?? messages[defaultLocale][key] ?? key;

    return Object.entries(replacements).reduce(
        (value, [name, replacement]) => value.replaceAll(`{${name}}`, replacement),
        text,
    );
}

export function useI18n() {
    const locales = computed(() => [
        { value: 'zh-CN', label: messages[locale.value]['locale.zh'] },
        { value: 'en-US', label: messages[locale.value]['locale.en'] },
    ]);

    return {
        locale,
        locales,
        t: translate,
    };
}
